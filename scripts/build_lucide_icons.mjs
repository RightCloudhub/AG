#!/usr/bin/env node
// Generate web/static/vendor/lucide-icons.js: the vendored subset of the Lucide icon set the
// workspace draws with. The brief fixes the icon library (Prompt.md §3.3: Lucide, 16px, 1.5 stroke)
// and the workspace is zero-build, so the geometry is checked in and never fetched at runtime.
// Dev tooling only - the browser loads the generated ESM file directly.
//
//   node scripts/build_lucide_icons.mjs --source <lucide-static>/icon-nodes.json --version 1.65.0
//   node scripts/build_lucide_icons.mjs --check --source <lucide-static>/icon-nodes.json
//
// The manifest below is the single source of truth for which icons are vendored: the generated file
// carries both the app's name -> id table and the geometry, so no id is written twice in the tree.
// `--check` writes nothing and exits 1 when the checked-in file differs from the pinned package.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'web/static/vendor/lucide-icons.js');

/** The app's icon names, each drawn from the Lucide icon named by the value (canonical Lucide ids). */
const ICONS = {
  chat: 'message-square', // a saved question, in the notebook and in the palette
  graph: 'network', // the graph view and the subgraph tab
  knowledge: 'database', // the knowledge-base scope and the library view
  review: 'check-check', // the review queue
  ops: 'activity', // operations
  plus: 'plus',
  close: 'x',
  stop: 'square', // the stop button while a run streams
  guide: 'book-open', // the /指南 command
  plan: 'git-branch', // plan mode and the /计划 command
  copy: 'copy',
  thumbUp: 'thumbs-up',
  thumbDown: 'thumbs-down',
  chevronDown: 'chevron-down',
  arrowRight: 'arrow-right',
  arrowUp: 'arrow-up', // also the send button
  arrowDown: 'arrow-down',
  menu: 'menu',
  info: 'info',
  warning: 'triangle-alert',
  search: 'search',
  refresh: 'rotate-ccw', // reload a list, retry a hop, ask again
  upload: 'upload',
  check: 'check',
  contrast: 'sun-moon', // the theme toggle
  settings: 'settings-2',
  kebab: 'ellipsis', // an overflow menu
  grip: 'grip-vertical', // a drag handle
  edit: 'pencil', // edit the question title
  filter: 'funnel', // focus one hop
  flash: 'zap', // the retrieval-cache note
  panelRightClose: 'panel-right-close', // collapse the inspector
  panelRightOpen: 'panel-right-open', // reopen it from the strip
};

/** Node kinds <ag-icon> can render. */
const USABLE = new Set(['path', 'circle', 'rect', 'ellipse', 'line', 'polyline', 'polygon']);

const argv = process.argv.slice(2);
const flag = name => argv.includes(name);
const value = name => {
  const at = argv.indexOf(name);
  return at === -1 ? '' : (argv[at + 1] ?? '');
};
const VERSION = value('--version') || '1.65.0';
const SOURCE = value('--source') || process.env.LUCIDE_ICON_NODES || '';

if (!SOURCE) {
  console.error('usage: node scripts/build_lucide_icons.mjs --source <path to lucide icon-nodes.json>');
  process.exit(2);
}

const nodes = JSON.parse(readFileSync(SOURCE, 'utf8'));
const problems = [];
const ids = new Map();
for (const [name, id] of Object.entries(ICONS)) {
  const data = nodes[id];
  if (!Array.isArray(data) || !data.length) {
    problems.push(`${name} -> ${id} is not in the source package`);
    continue;
  }
  for (const [tag] of data) if (!USABLE.has(tag)) problems.push(`${id} uses <${tag}>`);
  if (ids.has(id)) {
    problems.push(`${name} and ${ids.get(id)} both map to ${id}`);
    continue;
  }
  ids.set(id, name);
}
if (problems.length) {
  console.error(`the manifest does not match the source package:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const pairs = [...ids.entries()].sort(([a], [b]) => (a < b ? -1 : 1));
const header = [
  `// Lucide icon geometry, vendored subset (lucide v${VERSION}, ISC licence, lucide.dev).`,
  "// Generated by scripts/build_lucide_icons.mjs from the package's icon-nodes.json: never edit by",
  '// hand. The workspace is zero-build, so the paths are checked in rather than fetched at runtime.',
  `// Regenerate: node scripts/build_lucide_icons.mjs --source <lucide-static>/icon-nodes.json --version ${VERSION}`,
  '// ICON_IDS maps the app\'s icon names onto Lucide ids; LUCIDE holds each icon\'s own [tag, attrs]',
  '// node list on the 24-unit grid, which <ag-icon> draws at the 1.5 stroke the brief fixes.',
  '',
].join('\n');
const table = `export const ICON_IDS = {\n${pairs.map(([id, name]) => `  ${name}: '${id}',`).join('\n')}\n};\n`;
const geometry = `/**\n * One icon's nodes: [tag, attributes] pairs on the 24-unit grid.\n * @type {Record<string, ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>>}\n */\nexport const LUCIDE = {\n${pairs.map(([id]) => `  '${id}': ${JSON.stringify(nodes[id])},`).join('\n')}\n};\n`;

const file = `${header}${table}\n${geometry}`;
const current = (() => {
  try {
    return readFileSync(OUT, 'utf8');
  } catch {
    return '';
  }
})();

if (flag('--check')) {
  if (current === file) {
    console.log(`OK   ${pairs.length} icons, lucide v${VERSION}, vendored file is current`);
    process.exit(0);
  }
  console.error(`FAIL ${OUT} differs from lucide v${VERSION} - rerun the generator`);
  process.exit(1);
}

writeFileSync(OUT, file);
console.log(`wrote ${OUT} (${pairs.length} lucide icons, v${VERSION})`);
